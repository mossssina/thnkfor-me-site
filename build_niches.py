def _border():
    s = Side(style="thin", color="DEDEDE")
    return Border(left=s, right=s, top=s, bottom=s)

def _fill(c): return PatternFill("solid", fgColor=c)
def _font(bold=False, color="1C1C1C", size=10): return Font(name="Arial", bold=bold, color=color, size=size)
def _align(h="left", v="center", wrap=True): return Alignment(horizontal=h, vertical=v, wrap_text=wrap)

